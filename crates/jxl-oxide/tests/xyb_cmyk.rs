#[test]
fn xyb_encoded_cmyk_not_inverted() {
    let expected = [
        ((4usize, 4usize), [255u8, 255, 255]),
        ((4, 12), [6, 255, 255]),
        ((4, 20), [255, 0, 255]),
        ((12, 4), [255, 255, 0]),
        ((12, 12), [0, 0, 0]),
        ((12, 20), [129, 188, 225]),
    ];

    for request_srgb in [false, true] {
        let mut image = JxlImage::builder().read(Cursor::new(XYB_CMYK_JXL)).unwrap();
        assert!(image.image_header().metadata.xyb_encoded);
        if request_srgb {
            image.request_color_encoding(EnumColourEncoding::srgb(RenderingIntent::Relative));
        }

        let render = image.render_frame(0).unwrap();
        let fb = render.image_all_channels();
        let w = fb.width();
        let ch = fb.channels();
        let buf = fb.buf();

        for ((y, x), exp) in expected {
            let idx = (y * w + x) * ch;
            let got = [
                (buf[idx].clamp(0.0, 1.0) * 255.0).round() as u8,
                (buf[idx + 1].clamp(0.0, 1.0) * 255.0).round() as u8,
                (buf[idx + 2].clamp(0.0, 1.0) * 255.0).round() as u8,
            ];
            for c in 0..3 {
                assert!(
                    got[c].abs_diff(exp[c]) <= 2,
                    "request_srgb={request_srgb} at ({x},{y}): got {got:?}, expected ~{exp:?}"
                );
            }
        }
    }
}
